function legacyTopic(card: StudyCard): TopicId {
  const index = Number(card.id.replace('ai4sec-', ''));
  if (card.category === 'vulnerabilities' && index >= 27) return 'malware-analysis';
  if (card.category === 'operations' && (index === 33 || index === 38)) return 'threat-intelligence';
  if (card.category === 'operations' && (index === 34 || index === 36)) return 'security-rag';
  return defaultTopic(card.category);
}

function legacySource(card: StudyCard): CardSource {
  return {
    id: 'original',
    title: 'AI4SEC 自编起步题',
    url: '',
    type: '自编题',
    evidence: 'application',
    sourceCardId: card.id,
  };
}

export function normalizeBanks(legacyCards: StudyCard[]): StudyCard[] {
  const aliasMap = new Map(aliases.map((alias) => [alias.source, alias.canonical]));
  const legacyAreas: Record<string, string> = scopeFile.cards;
  const all: StudyCard[] = legacyCards.map((card) => ({
    ...card,
    topic: legacyTopic(card),
    knowledgeArea: legacyAreas[card.id] as KnowledgeAreaId | undefined,
    sources: [legacySource(card)],
  }));

  for (const bank of questionBanks) {
    for (const card of bank.cards) {
      all.push({
        id: card.id,
        category: card.category,
        question: card.question,
        answer: card.answer,
        createdAt: 0,
        topic: card.topic ?? sourceTopics[bank.source.id] ?? defaultTopic(card.category),
        knowledgeArea: card.knowledgeArea ?? (legacyAreas[card.id] as KnowledgeAreaId | undefined) ?? bank.source.knowledgeArea,
        subtopic: card.subtopic,
        knowledgePoint: card.knowledgePoint,
        questionType: card.questionType,
        origin: card.origin,
        level: card.level,
        tags: card.tags,
        explanation: card.explanation,
        example: card.example,
        sources: [{
          id: card.referenceId ?? bank.source.id,
          title: card.referenceTitle ?? bank.source.title,
          url: card.reference ?? bank.source.url,
          type: card.referenceType ?? bank.source.type,
          evidence: card.evidence,
          sourceCardId: card.id,
        }, ...(card.supportingReferences ?? []).map((reference) => ({
          ...reference,
          sourceCardId: card.id,
        }))],
      });
    }
  }

  const byId = new Map(all.map((card) => [card.id, card]));
  const splitSources = new Set(splits.map((split) => split.source));
  const groups = new Map<string, StudyCard[]>();
  for (const card of all) {
    if (splitSources.has(card.id)) continue;
    const canonical = aliasMap.get(card.id) ?? card.id;
    const group = groups.get(canonical) ?? [];
    group.push(card);
    groups.set(canonical, group);
  }

  return Array.from(groups, ([canonical, group]) => {
    const primary = byId.get(canonical);
    if (!primary) throw new Error(`Unknown canonical card: ${canonical}`);
    const enrich = group.find((card) => card.explanation);
    const splitTargets = splits.flatMap((split) => split.targets
      .filter((target) => target.id === canonical)
      .map((target) => ({ target, source: byId.get(split.source) })));
    if (splitTargets.some((item) => !item.source)) throw new Error(`Unknown split source for: ${canonical}`);
    const splitTarget = splitTargets[0]?.target;
    const explanation = primary.explanation ?? splitTarget?.explanation ?? enrich?.explanation;
    const example = primary.example ?? splitTarget?.example ?? enrich?.example;
    return {
      ...primary,
      subtopic: primary.subtopic ?? splitTarget?.subtopic ?? enrich?.subtopic,
      knowledgePoint: primary.knowledgePoint ?? splitTarget?.knowledgePoint ?? enrich?.knowledgePoint,
      questionType: primary.questionType ?? splitTarget?.questionType ?? enrich?.questionType,
      origin: primary.origin ?? (splitTarget ? '自行整理' as const : group.find((card) => card.origin)?.origin),
      explanation,
      example,
      alternateQuestions: Array.from(new Set(group.map((card) => card.question).filter((value) => value !== primary.question))),
      otherExplanations: Array.from(new Set(group.map((card) => card.explanation).filter((value): value is string => Boolean(value) && value !== explanation))),
      otherExamples: Array.from(new Set(group.map((card) => card.example).filter((value): value is string => Boolean(value) && value !== example))),
      level: primary.level ?? (splitTarget?.level as StudyCard['level']) ?? enrich?.level,
      tags: Array.from(new Set([...group.flatMap((card) => card.tags ?? []), ...(splitTarget?.tags ?? [])]
        .map(normalizeTag).filter(Boolean))),
      sources: [...group.flatMap((card) => card.sources ?? []),
        ...splitTargets.flatMap((item) => item.source?.sources ?? [])],
    };
  });
}
